/**
 * An impossible measurement: boarding a passenger who never arrived, a percentile outside
 * `[0, 100]`, a run record whose seed is missing.
 *
 * Thrown rather than returned, for the same reason `ModelError` is: a metric that silently
 * absorbs a contradiction becomes a confidently wrong number, which is the single failure
 * mode CLAUDE.md § Statistical discipline exists to prevent.
 */
export class MetricsError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'MetricsError';
  }
}

/**
 * Format version of {@link RunRecord} on disk.
 *
 * Bumped whenever a stored record's shape changes in a way that an older reader would
 * misinterpret. `parseRunRecord` refuses a version it does not know rather than guessing,
 * because a mis-parsed run record produces plausible statistics from the wrong data.
 */
export const METRICS_SCHEMA_VERSION = 1;

/* -------------------------------------------------------------------------- *
 * Percentiles
 * -------------------------------------------------------------------------- */

/**
 * How a percentile falls between two order statistics.
 *
 * Percentile is not one function — the literature has at least nine — so the method is
 * carried on every result that used it rather than being an unstated house convention. WT95
 * from two tools that disagree on interpolation is not a reproducibility bug anyone enjoys
 * finding.
 *
 * - `linear` — **the default.** Hyndman & Fan type 7, which is what NumPy, R's default and
 *   Excel's `PERCENTILE.INC` compute. The percentile at `p` sits at position
 *   `h = (n - 1) * p / 100` in the ascending order statistics, linearly interpolated between
 *   `x[floor(h)]` and `x[floor(h) + 1]`. Continuous in `p`, which matters because WT95 is
 *   compared between configurations that differ by fractions of a second.
 * - `nearest-rank` — the classical definition: the smallest observed value at or below which
 *   at least `p`% of the sample falls, i.e. `x[ceil(n * p / 100) - 1]`. Always an observed
 *   value, never interpolated. Discontinuous in `n`, so two runs with different passenger
 *   counts can report percentiles that jump; offered because some lift-industry reporting
 *   uses it and cross-checks need it.
 */
export const PERCENTILE_METHODS = ['linear', 'nearest-rank'] as const;

export type PercentileMethod = (typeof PERCENTILE_METHODS)[number];

/** Hyndman & Fan type 7. See {@link PERCENTILE_METHODS}. */
export const DEFAULT_PERCENTILE_METHOD: PercentileMethod = 'linear';

/* -------------------------------------------------------------------------- *
 * Histograms
 * -------------------------------------------------------------------------- */

/**
 * One bucket of a {@link Histogram}.
 *
 * Half-open `[lowerBound, upperBound)`, except the final bin of a histogram, which is closed
 * at the top so the maximum observation lands somewhere. {@link count} is how many samples
 * fell here; {@link weight} is their total weight, which for a time-weighted distribution is
 * **seconds**, not samples.
 */
export interface HistogramBin {
  readonly lowerBound: number;
  readonly upperBound: number;
  readonly count: number;
  readonly weight: number;
  /** `weight / totalWeight`, or `0` when the histogram is empty. */
  readonly fraction: number;
}

/**
 * A binned distribution, optionally weighted.
 *
 * Weighting is what makes "car occupancy over time" honest. A car that sits at 0.9 for two
 * minutes and at 0.1 for one second visited two load levels equally often and spent 99.2% of
 * its time full; an unweighted histogram of the samples would call that an even split. See
 * {@link LoadFactorStatistics}.
 */
export interface Histogram {
  readonly bins: readonly HistogramBin[];
  /** Samples that landed inside the bins. Excludes {@link underflow} and {@link overflow}. */
  readonly count: number;
  /** Total weight inside the bins. Equals {@link count} for an unweighted histogram. */
  readonly totalWeight: number;
  /** Samples below the first bin's lower bound. */
  readonly underflow: number;
  /** Samples above the last bin's upper bound. */
  readonly overflow: number;
  /** Weighted mean of the observations, or `NaN` when there are none. Not a bin midpoint. */
  readonly mean: number;
  /** Smallest observation, or `NaN` when there are none. */
  readonly min: number;
  /** Largest observation, or `NaN` when there are none. */
  readonly max: number;
}

/* -------------------------------------------------------------------------- *
 * Trend
 * -------------------------------------------------------------------------- */

/** An ordinary-least-squares fit of `y = intercept + slope * x`. */
export interface LinearTrend {
  readonly n: number;
  /** Units of `y` per unit of `x`. */
  readonly slope: number;
  readonly intercept: number;
  /** Coefficient of determination, `0` when `y` has no variance. */
  readonly rSquared: number;
  /**
   * Residual standard deviation about the fitted line, in units of `y`
   * (`sqrt(RSS / (n - 2))`). `Infinity` for `n < 3`.
   *
   * This is the scatter the fit did **not** explain, and unlike {@link standardError} it is
   * not an inference statistic, so autocorrelation does not corrupt it: it is simply how far
   * the observations sit from the line. {@link SaturationThresholds.minGrowthToNoiseRatio}
   * uses it as the noise yardstick that the fitted growth has to beat.
   */
  readonly residualStdDev: number;
  /**
   * Standard error of {@link slope}, under the OLS assumption of independent residuals.
   *
   * `Infinity` for `n < 3` (no residual degrees of freedom). Queue-length series violate the
   * independence assumption badly — see {@link SaturationThresholds.minTStatistic}.
   */
  readonly standardError: number;
  /** `slope / standardError`. `0` when the slope is exactly zero. */
  readonly tStatistic: number;
  readonly meanX: number;
  readonly meanY: number;
}

/* -------------------------------------------------------------------------- *
 * Per-passenger records
 * -------------------------------------------------------------------------- */

/**
 * One leg of one passenger's journey, as recorded.
 *
 * This is the atom the whole metrics module is built from, and it is deliberately **raw**:
 * timestamps, not durations. `waitSeconds` is not a field because it is
 * `boardedAt - arrivedAt` and storing both invites the two to disagree after a hand edit or a
 * schema migration. Use {@link waitSecondsOf}, {@link rideSecondsOf} and
 * {@link legSecondsOf}.
 *
 * A leg with no {@link boardedAt} was still waiting when the run ended — which is
 * information, not an omission: unserved passengers are exactly the signature of saturation,
 * and they must survive into the record so `detectSaturation` can see them.
 *
 * Journey identity ({@link journeyId}) is what makes time-to-destination span a sky-lobby
 * transfer; see {@link JourneyRecord}.
 */
export interface PassengerRecord {
  /** Identity of *this leg*, unique within a run. `Passenger.id`. */
  readonly passengerId: string;
  /** Identity of the whole journey, stable across sky-lobby transfers. */
  readonly journeyId: string;
  /** 0 for the first leg, incrementing at each transfer. */
  readonly legIndex: number;
  /** Whether this leg ends at the journey's final destination. */
  readonly isFinalLeg: boolean;

  readonly originFloorId: string;
  /** Where *this leg* ends — the sky lobby, on a leg that transfers. */
  readonly destinationFloorId: string;
  /** Where the whole journey ends. Equal to {@link destinationFloorId} on the final leg. */
  readonly finalDestinationFloorId: string;
  readonly direction: Direction;

  /** Body mass in kilograms, as drawn from the `passengerMass` stream. */
  readonly massKg: number;
  readonly credentialGroup?: CredentialGroup | undefined;

  /**
   * When this leg's wait began — registration at the landing.
   *
   * **The window membership key.** Dispatcher-independent, so the same passenger falls in the
   * same window under every configuration being compared. See the module docstring.
   */
  readonly arrivedAt: SimTime;
  /** When the whole journey began. Equal to {@link arrivedAt} on the first leg. */
  readonly journeyStartedAt: SimTime;
  /**
   * Seconds of declared non-lift travel owed **after** this leg alights, when the journey's last
   * segment is the building's escalator or stair rather than a lift.
   *
   * **Absent, not `0`, on every leg that owes none**, which is every leg of every building that
   * declares no `transportModes` — so a record from such a run is the object it was before this
   * field existed. {@link buildJourneys} adds it to the completion instant, which is what stops
   * removing a spurious lift leg from silently handing the passenger free seconds.
   */
  readonly egressTransitSeconds?: number | undefined;
  /** When the passenger entered the car, or absent if they were never served. */
  readonly boardedAt?: SimTime | undefined;
  /** When the passenger left the car, or absent if they never boarded or never arrived. */
  readonly alightedAt?: SimTime | undefined;
  /**
   * When the passenger **gave up and left the landing**, on a run that declares `sim.patience`
   * (docs/14 § 3.1).
   *
   * **Absent on every leg that did not abandon**, which is every leg of every run that declares no
   * patience — so such a record is the object it was before this field existed. Never present
   * beside {@link boardedAt}: a passenger who boarded did not abandon, and the recorder refuses
   * the combination rather than storing it.
   *
   * A leg carrying this is **not served and not censored** — it is a third outcome. AWT averages
   * the legs that boarded, and an abandoned leg is one whose long wait has been deleted from that
   * average by the passenger walking away, which is why `RunSummary.abandonment` has to be read
   * beside the mean and why `awtIsValid` refuses the mean outright once the rate is high enough.
   */
  readonly abandonedAt?: SimTime | undefined;
  /**
   * When the building **turned this leg away for want of a credential** (`DECISIONS.md` § D266).
   *
   * **Absent on every leg that was not refused**, which is every leg of every building that
   * declares no `accessZones` and every leg whose rider is correctly badged — so such a record is
   * the object it was before this field existed. Never present beside {@link boardedAt}: a
   * passenger the readers refused did not ride, and the recorder refuses the combination rather
   * than storing it.
   *
   * Equal to {@link arrivedAt} on every leg that carries it today, because the model asks the
   * credential question when the rider reaches the landing rather than when a car does. It is a
   * time rather than a flag so that a later model which reads badges further down the journey
   * writes a record this one can still be compared against.
   *
   * A leg carrying this is **not served and not censored** — a third outcome, the same shape
   * {@link abandonedAt} is. The difference from abandonment is the direction of the bias and it is
   * the reason the two are not one field: an abandoned leg deletes a *long* wait from the average,
   * and a refused leg deletes a wait that never started. Both leave the mean describing fewer
   * people than arrived, which is why the counts are published beside it
   * (`ConservationAudit.accessRefused`).
   */
  readonly refusedAt?: SimTime | undefined;
  /** The car that served this leg, when known. */
  readonly carId?: string | undefined;
  /** The bank that served this leg, when known. */
  readonly bankId?: string | undefined;

  /**
   * The car the landing panel named, under destination *dispatch* only.
   *
   * Absent under every conventional and disclosure-only run, so a schema-version-1 record is
   * byte-identical to one written before this field existed. Where it is present,
   * `assignedCarId === carId` for every leg that boarded — a wrong-car boarding is a
   * conservation failure, not a statistic, and `Simulation` asserts it rather than reporting it.
   */
  readonly assignedCarId?: string | undefined;
  /** When the panel named a car. Between {@link arrivedAt} and {@link boardedAt}, always. */
  readonly assignedAt?: SimTime | undefined;
}

/** Seconds spent waiting at the landing on this leg, or `undefined` if never served. */
export function waitSecondsOf(record: PassengerRecord): number | undefined {
  return record.boardedAt === undefined ? undefined : record.boardedAt - record.arrivedAt;
}

/** Seconds spent in the car on this leg, or `undefined` until the passenger alights. */
export function rideSecondsOf(record: PassengerRecord): number | undefined {
  if (record.boardedAt === undefined || record.alightedAt === undefined) return undefined;
  return record.alightedAt - record.boardedAt;
}

/** Wait plus ride for this leg alone, or `undefined` until the passenger alights. */
export function legSecondsOf(record: PassengerRecord): number | undefined {
  return record.alightedAt === undefined ? undefined : record.alightedAt - record.arrivedAt;
}

/**
 * Every leg of one journey, and the journey-level timings that only exist across legs.
 *
 * Built by `buildJourneys()` from the flat leg records — the module never stores journeys,
 * because a journey is a *view* of its legs and storing it would duplicate them.
 *
 * This type is the reason `journeyId` exists. docs/03-traffic-and-statistics.md makes
 * time-to-destination a headline metric ("what destination dispatch optimizes; AWT alone
 * unfairly penalizes it"), and in a sky-lobby building the destination is two rides and a
 * walk away. Reporting the final leg's own duration as TTD would flatter every mixed-use
 * tower by hiding the first wait, the shuttle ride and the transfer.
 */
export interface JourneyRecord {
  readonly journeyId: string;
  /** The legs, ascending by `legIndex`. Always at least one. */
  readonly legs: readonly PassengerRecord[];
  readonly legCount: number;
  /** Origin of the first leg. */
  readonly originFloorId: string;
  /** Final destination as declared by the legs. */
  readonly finalDestinationFloorId: string;
  /**
   * When the journey began: the first leg's `arrivedAt`.
   *
   * **The window membership key for a journey**, so a journey belongs to exactly one window
   * however many legs it has.
   */
  readonly startedAt: SimTime;
  /** When the final leg alighted, or `undefined` while the journey is incomplete. */
  readonly completedAt?: SimTime | undefined;
  /** Whether a final leg exists *and* has alighted. */
  readonly isComplete: boolean;
  /**
   * Arrival at the first landing to alighting at the final one, **including** every transfer
   * wait and walk. `undefined` until the journey completes.
   *
   * A passenger standing in a sky lobby waiting for the second car has no time-to-destination
   * yet, and reporting the first leg's duration as one would be a lie in the flattering
   * direction.
   */
  readonly timeToDestinationSeconds?: number | undefined;
  /** Sum of the legs' waiting times, over the legs that boarded. */
  readonly totalWaitSeconds: number;
  /** Sum of the legs' ride times, over the legs that completed. */
  readonly totalRideSeconds: number;
  /**
   * Time spent neither waiting nor riding: walking across sky lobbies between legs.
   * `undefined` until the journey completes.
   */
  readonly transferSeconds?: number | undefined;
}

/* -------------------------------------------------------------------------- *
 * Samples
 * -------------------------------------------------------------------------- */

/**
 * What one car's load cell read at one instant.
 *
 * Sampled at load-change events, not on a timer: between two events the load is constant, so
 * an event-driven sample is exact rather than approximate. `summarize` treats the series as a
 * step function and weights each sample by the seconds until the next one for the same car —
 * which is why sampling on every board and alight is both sufficient and correct, and why a
 * sample taken before the report window still counts (its value holds into the window).
 */
export interface LoadSample {
  readonly at: SimTime;
  readonly carId: string;
  /** `massKg / ratedLoadKg`. Can exceed 1: 1.1 is the overload alarm, not the ceiling. */
  readonly loadFactor: number;
  readonly occupants: number;
  readonly massKg: number;
}

/** The three numbers a {@link LoadSample} needs from a car. `CarLoadSnapshot` satisfies it. */
export interface LoadReading {
  readonly loadFactor: number;
  readonly occupants: number;
  readonly massKg: number;
}

/* -------------------------------------------------------------------------- *
 * Travel and energy
 * -------------------------------------------------------------------------- */

/**
 * Standard gravity, m/s². The only physical constant the energy proxy needs.
 *
 * CODATA / ISO 80000-3's conventional value. Named rather than inlined so the arithmetic below
 * can be read against the formula it implements.
 */
export const STANDARD_GRAVITY_MPS2 = 9.80665;

/**
 * **The counterweight balance ratio: the fraction of rated load the counterweight carries on
 * top of the car's own mass.**
 *
 * 0.5 — the near-universal traction-lift convention. The counterweight is sized at
 * `car mass + 0.4…0.5 × rated load`, so the drive sees zero static out-of-balance at half load
 * and its worst case (full car up, empty car down) is symmetric. Sources: Barney & Al-Sharif,
 * *Elevator Traffic Handbook* § on drive sizing and counterbalancing; CIBSE Guide D § 13 on
 * lift power and energy; ISO 25745-2, whose reference-cycle energy measurement is taken at
 * empty, half and full load precisely because the mid point is the balance point. See
 * docs/02-elevator-reference.md.
 *
 * **Why 0.5 and not 0.45.** The range in the literature is 0.4–0.5 and real installations vary.
 * 0.5 is chosen because it is the value at which the proxy is *symmetric* — an empty car and a
 * full car of the same travel cost the same — which makes the number a statement about how far
 * cars drove out of balance rather than about a particular machine's counterweight order. A
 * proxy whose value depended on an unmeasured per-installation choice would put a fitted
 * constant inside a published axis.
 *
 * Not a tunable (CLAUDE.md invariant 7 governs *dispatch strategy*, which is data; this is
 * reference data about the machine) and deliberately not configurable: a per-run counterweight
 * ratio would let two arms of one comparison be scored on different scales.
 */
export const COUNTERWEIGHT_BALANCE_RATIO = 0.5;

/**
 * One completed car move, as the energy proxy reads it.
 *
 * Recorded **per move**, not per run, for one reason that decides the whole design: every other
 * statistic in a {@link RunSummary} is computed over a reporting window, and the shipped
 * operating points report a 300 s peak out of a 900 s run. A cumulative odometer read at the
 * end would put a whole-run energy figure beside a peak-window AWT in the same Pareto point,
 * and the two would not be describing the same 300 seconds. A per-move sample windows exactly
 * as a {@link LoadSample} does.
 *
 * **Attributed at arrival**, i.e. `at` is the moment the car levelled, not the moment it
 * started. The move is charged to the window it *ended* in. Stated rather than left implicit:
 * a move that straddles the window boundary is charged whole to one side, exactly as a leg is
 * assigned whole to the window its arrival falls in.
 */
export interface TravelSample {
  readonly at: SimTime;
  readonly carId: string;
  /** Metres travelled on this move. Always positive; {@link direction} carries the sign. */
  readonly distanceM: number;
  readonly direction: Direction;
  /** Passenger mass aboard for the move, kg. Load only changes at a stop, so this is exact. */
  readonly loadKg: number;
  /** The car's rated load, kg. The counterweight's reference. */
  readonly ratedLoadKg: number;
  /**
   * **The energy proxy for this move, in joules of out-of-balance mechanical work.**
   *
   * `|loadKg − COUNTERWEIGHT_BALANCE_RATIO · ratedLoadKg| · g · distanceM`.
   *
   * The absolute value is the **non-regenerative** convention: a drive without regeneration
   * dissipates the overhauling direction in a brake resistor rather than returning it, so both
   * directions cost. ISO 25745-2 measures a non-regenerative unit exactly this way, and it is
   * the conservative choice — a regenerative drive's figure is bounded above by this one.
   *
   * **What it deliberately omits, so nobody reads it as kWh:** acceleration losses (which need
   * the car and counterweight masses, which no shipped spec carries), drive and gearing
   * efficiency, door-motor energy, and standby/idle power — ISO 25745-2's other half, which on
   * a lightly-used lift dominates the running term and is a property of the *machine*, not of
   * the dispatcher. This is a proxy for *the work the dispatch decisions caused*, and that is
   * the quantity a Pareto front over dispatchers is asking about. {@link EnergyStatistics}
   * reports the stops and the metres beside it so a reader can see which one moved.
   */
  readonly workJ: number;
}

/** The four numbers a {@link TravelSample} needs from a car after a move. */
export interface TravelReading {
  readonly distanceM: number;
  readonly direction: Direction;
  readonly loadKg: number;
  readonly ratedLoadKg: number;
}

/** `|load − ratio·rated| · g · distance`, in joules. Pure and total. See {@link TravelSample.workJ}. */
export function outOfBalanceWorkJ(reading: TravelReading): number {
  const netKg = Math.abs(reading.loadKg - COUNTERWEIGHT_BALANCE_RATIO * reading.ratedLoadKg);
  return netKg * STANDARD_GRAVITY_MPS2 * Math.abs(reading.distanceM);
}

/**
 * What the fleet spent moving, over the reporting window.
 *
 * The third Pareto axis (docs/06 § Guardrails, CLAUDE.md § Tuning discipline: *"Report the
 * Pareto front over (AWT, energy, WT95)"*). Before this existed the axis was a declared seam
 * with nothing filling it, and the front silently degenerated to two objectives.
 *
 * ## Three numbers, not one
 *
 * {@link workKJ} is the axis. {@link distanceM} and {@link starts} are published beside it
 * because they are the two things that can move it, and a single scalar cannot say which: a
 * dispatcher that cut energy by carrying fuller cars and one that cut it by driving less are
 * different findings with the same number. {@link workPerServedLegKJ} divides the work by the
 * **legs delivered** rather than leaving it as a fleet total, and it exists because the total is
 * trivially gameable in the wrong direction: *a configuration that spends less because it served
 * fewer people has not saved anything.* A saturating dispatcher whose queues diverge drives less
 * and therefore scores better on {@link workKJ}, which is exactly the arm a three-axis front must
 * not reward. The per-leg figure is the one that cannot be improved by refusing work.
 *
 * ## `NaN`, never `0`, when nothing was recorded
 *
 * A record written before travel sampling existed, or by a harness that does not sample, has
 * no travel samples — and "the cars did not move" and "nobody wrote down how far the cars
 * moved" are different facts. {@link measured} says which. Zeroing them would make every arm
 * tie on energy and quietly restore a two-axis front under a three-axis name, which is exactly
 * what `pareto.ts` refused to do when the proxy was absent.
 */
export interface EnergyStatistics {
  /** Whether the run recorded any travel at all. `false` ⇒ every figure below is `NaN`. */
  readonly measured: boolean;
  /** Out-of-balance mechanical work over the window, kilojoules. The Pareto energy axis. */
  readonly workKJ: number;
  /** Metres the fleet travelled in the window, summed over cars. */
  readonly distanceM: number;
  /** Moves commanded in the window. Each is one motor start. */
  readonly starts: number;
  /** {@link workKJ} per leg that alighted in the window. `NaN` when none did. */
  readonly workPerServedLegKJ: number;
  /** Cars that moved at least once in the window. */
  readonly movingCarCount: number;
}

/**
 * How many people were waiting, building-wide, at one instant.
 *
 * The input to saturation detection. Explicit samples are preferred, because only the
 * simulation knows about passengers who left the queue for a reason other than boarding; when
 * a record has none, `queueLengthSeries()` derives an equivalent series from the arrival and
 * boarding times in the passenger records.
 */
export interface QueueSample {
  readonly at: SimTime;
  /** Total passengers waiting at landings. */
  readonly waiting: number;
  /** Optional per-floor breakdown, for diagnosing *where* a queue diverges. */
  readonly byFloorId?: Readonly<Record<string, number>> | undefined;
}

/* -------------------------------------------------------------------------- *
 * Windows
 * -------------------------------------------------------------------------- */

/**
 * A reporting window, half-open in simulated seconds: `[startS, endS)`.
 *
 * The rise-and-fall template reports the **peak 5 minutes**, not the whole run
 * (docs/03-traffic-and-statistics.md § Part 1), so the window is a first-class value that
 * travels with every summary rather than an implicit assumption about which numbers mean
 * what.
 */
export interface ReportWindow {
  /** Label for reporting, e.g. `full-run`, `peak-5min`. */
  readonly id: string;
  /** Inclusive lower bound. */
  readonly startS: SimTime;
  /** Exclusive upper bound. */
  readonly endS: SimTime;
}

/** Seconds spanned by a window. */
export function windowDurationS(window: ReportWindow): number {
  return window.endS - window.startS;
}

/** Whether an instant falls in `[startS, endS)`. */
export function windowContains(window: ReportWindow, at: SimTime): boolean {
  return at >= window.startS && at < window.endS;
}

/**
 * Whether a leg belongs to a window — **by arrival time**, never by boarding or alighting.
 *
 * See the module docstring: arrival times come from the traffic model and are identical
 * across the configurations being compared, so window membership cannot be shifted by the
 * thing under test.
 */
export function windowContainsArrival(window: ReportWindow, record: PassengerRecord): boolean {
  return windowContains(window, record.arrivedAt);
}

/** Whether a journey belongs to a window, by the arrival time of its first leg. */
export function windowContainsJourney(window: ReportWindow, journey: JourneyRecord): boolean {
  return windowContains(window, journey.startedAt);
}

