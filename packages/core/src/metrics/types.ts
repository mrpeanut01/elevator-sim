/**
 * The timings of the cars serving a terminal, as the run actually ran them.
 *
 * Physical provenance, not a metric option: it is what the doors and the machine were
 * configured to do. One consumer today — `achievedIntervalOf` derives its departure-clustering
 * threshold from it (see `departureGapBracket`), because that threshold is a **property of the
 * building's doors** and cannot honestly be a constant.
 *
 * Where a bank's cars differ, or several banks serve the same terminal, supply the **worst
 * case**: the largest `doorOpenS`, `doorCloseS`, dwell and `fullLoadTransferS` (which push
 * the reopen bound up) and the *shortest* `nearestFloorFlightS` (which pulls the round-trip
 * bound down). Both directions make the derived threshold more conservative, and a threshold
 * that is safe for the worst car is safe for all of them.
 */
export interface CarTimings {
  /** Seconds from fully closed to fully open. */
  readonly doorOpenS: number;
  /** Seconds from fully open to fully closed. */
  readonly doorCloseS: number;
  /** Dwell when the stop answers a hall call, seconds. */
  readonly dwellHallCallS: number;
  /** Dwell when the stop answers a car call, seconds. */
  readonly dwellCarCallS: number;
  /**
   * `P · tp` — seconds a full design load takes to transfer.
   *
   * The dwell a stop actually gets is `max(policy dwell, transfer)`, so at the terminal under
   * up-peak this, not the policy dwell, is usually what holds the doors.
   */
  readonly fullLoadTransferS: number;
  /**
   * Flight time from the terminal to the nearest floor the bank serves, seconds.
   *
   * **Jerk-limited** — `physics/motion`'s `travelTime`, not `distance / ratedSpeed`, which no
   * car achieves on a one-floor hop. Optional: without it the shortest-round-trip half of the
   * bracket cannot be computed, and `departureGapBracket` falls back to a margin above the
   * reopen bound instead of the bracket midpoint.
   */
  readonly nearestFloorFlightS?: number | undefined;
  /** Seconds between the doors being shut and the car moving. Treated as 0 when absent. */
  readonly motorStartDelayS?: number | undefined;
  /** Seconds between arriving at a floor and the doors starting to open. 0 when absent. */
  readonly levelingSettleS?: number | undefined;
}

/* -------------------------------------------------------------------------- *
 * The run record
 * -------------------------------------------------------------------------- */

/**
 * Everything one replication produced, and the seed that produced it.
 *
 * **CLAUDE.md invariant 5 lives on this type.** {@link seed} is not optional and is not a
 * convenience: it is what lets a stored record be replayed bit-for-bit
 * (`new StreamSet(runSeed(record))`), and `parseRunRecord` rejects a record without one
 * rather than loading a dataset nobody can reproduce.
 *
 * The seed is a **decimal string** because it is a 64-bit unsigned value: `bigint` does not
 * survive `JSON.stringify`, and `number` silently loses precision above 2^53. `runSeed()`
 * converts it back.
 *
 * **The seed alone stopped being sufficient in wave 13, and this type says so rather than
 * assuming it.** A run may now separate the crowd from the machine ({@link trafficSeed}) and may
 * declare which draw ordering produced it ({@link trafficModel}); both are inputs to the trace, so
 * a record that omitted either would still replay *deterministically* — to a different answer, off
 * a different set of passengers. That is the failure `experiments/reports/replay.ts` exists to
 * catch, and the reason both fields are stamped here rather than only on `SimulationResult`, which
 * dies with the process. Neither is *required*, because absence is the pre-flag default and has to
 * stay byte-identical to it; both are read back by `replaySimulationConfig`.
 */
export interface RunRecord {
  readonly schemaVersion: number;
  /**
   * Which passenger model produced this run — see `metrics/comparability.ts`.
   *
   * Absent means `conventional`, which is every run this project produced before destination
   * dispatch existed and every run that only *discloses* the destination. Present and equal to
   * `destination-dispatch` means the landing panel named a car per passenger, and nine of the
   * scalars derived from this record may not be paired against a record that does not say so.
   * Recorded rather than derived, because a stored record outlives the profile that made it.
   */
  readonly passengerModel?: PassengerModel | undefined;
  /** Identity of this replication, unique within an experiment. */
  readonly runId: string;
  /** The `StreamSet` master seed, as a decimal string. Invariant 5. */
  readonly seed: string;
  /**
   * The demand seed, as a decimal string — present only when the run was given one.
   *
   * The second half of invariant 5 on a run that separated the crowd from the machine (docs/14
   * § 1.1). {@link seed} alone does not reproduce such a run: the demand streams were derived from
   * *this* value, so a record carrying only the master seed replays a different crowd through the
   * same building.
   *
   * **Absent, never equal to {@link seed}, when the run was given none — and that records the
   * caller's intent, not a behavioural difference.** A traffic seed equal to the run seed produces
   * *the same run*: `StreamSet.#seedFor` hands the demand streams a bigint of the same value either
   * way, and `random/streams.test.ts` asserts it stream by stream ("is the identity when it equals
   * the run seed"). Measured end to end on garden-apartments at seed 20260731: 23 legs either way,
   * the passenger records equal, the whole record equal once this key is removed.
   *
   * So the key is provenance — *this run was authored as a crowd/machine split* — and it is kept
   * because it costs nothing: absent when unused, so a default run's record is byte-identical to
   * one written before the field existed. It is **not** kept because omitting it would replay a
   * different crowd; at a coinciding seed it would not. Where the seed differs from the run seed —
   * the case this field exists for — dropping it does replay a different crowd, and that is
   * measured in `experiments/reports/trafficModelReplay.test.ts`.
   */
  readonly trafficSeed?: string | undefined;
  /**
   * Which traffic draw ordering produced this run — **present only when it was not `v1`**.
   *
   * Recorded for the reason {@link passengerModel} is: a stored record outlives the build that
   * wrote it, and this one names *which simulator* the dataset came from. It is not a tunable. A
   * replay that dropped it would re-run the same building at the same seed against a different
   * trace — more than half the legs, measured — and report the divergence as a determinism failure
   * in `core` rather than as the incomplete record it is.
   *
   * Absent rather than `'v1'`, and that is a claim rather than a convenience: a `v1` run *is* the
   * run this repository produced before the option existed, same draws and same record, so
   * announcing `'v1'` would assert a distinction that does not exist and would add a key to every
   * pinned record to say nothing. Note this is the **opposite** boundary to {@link trafficSeed}'s,
   * which is omitted only when it was never given — the two are reasoned separately rather than by
   * analogy.
   */
  readonly trafficModel?: TrafficModelVersion | undefined;
  readonly buildingId?: string | undefined;
  readonly dispatcherProfileId?: string | undefined;
  readonly trafficProfileId?: string | undefined;
  readonly demandTemplateId?: string | undefined;
  /** Index of this replication within its batch, when it belongs to one. */
  readonly replication?: number | undefined;
  /** Population the demand was generated against, for handling capacity as % of population. */
  readonly population?: number | undefined;

  /** Simulated time the run started, in seconds. */
  readonly startedAt: SimTime;
  /**
   * Simulated time the run stopped — the horizon passed to `SimKernel.run(until)`.
   *
   * **Exclusive.** The full-run window is `[startedAt, endedAt)`, so pass the horizon you ran
   * to, not the timestamp of the last event; a passenger arriving at exactly `endedAt` falls
   * outside the window by the same half-open rule every other window obeys.
   */
  readonly endedAt: SimTime;
  /** The window this run intends to be reported over, when the demand template names one. */
  readonly reportWindow?: ReportWindow | undefined;

  /**
   * Non-fatal diagnostics the run raised, disclaimers first. Absent when there were none.
   *
   * **This is what makes a disclaimer travel with the data it disclaims.** Some of these do not
   * qualify a number, they say the number describes *different hardware or a different
   * building* — Vertical City's eight double-deck shuttles run as single-deck cars, so every
   * round-trip time, interval and handling capacity stored here is for a machine nobody
   * configured. A run whose record does not carry that is a record that reads as modelled, and
   * `serializeRunRecord` is `JSON.stringify(record)`: without this field the statement reached
   * `SimulationResult.warnings` in memory and the console, and nothing that outlived the
   * process.
   *
   * Optional, so every record written before the field existed still parses — and so a run with
   * nothing to say adds no key. Ordered rather than sorted on read: the producer puts
   * disclaimers ahead of advisories, because a consumer that truncates (the CLI does) must
   * truncate the advisories.
   *
   * It is **not** a substitute for {@link seed} (invariant 5) and does not participate in
   * replay: a replayed run re-derives its own warnings from the same configuration, so a
   * fingerprint over the record covers this field exactly as it covers every other one.
   */
  readonly warnings?: readonly string[] | undefined;

  /**
   * Every car in service during the run, whether or not it ever carried anybody.
   *
   * The fleet roster, not a derived list. `LoadFactorStatistics` needs it because an idle car
   * produces no {@link LoadSample} and would otherwise vanish from the occupancy
   * distribution, taking the evidence of over-provisioning with it — see that type. Optional
   * so a record written before the roster was tracked still parses; when it is absent the
   * cars seen in the samples are all the metric can know about.
   */
  readonly carIds?: readonly string[] | undefined;
  /**
   * Door and motion timings of the cars serving the terminal — see {@link CarTimings}.
   *
   * Optional, and the only metric that reads it is the achieved interval, which needs it to
   * derive its departure-clustering threshold rather than guess one. A record written without
   * it still parses and still summarizes; the interval then falls back to
   * `FALLBACK_DEPARTURE_GAP_S` and says so through
   * {@link IntervalStatistics.departureGapBasis}, which is the signal that the number came
   * from a constant instead of from this building.
   */
  readonly carTimings?: CarTimings | undefined;
  /** One entry per leg, in the order the legs arrived. */
  readonly passengers: readonly PassengerRecord[];
  readonly loadSamples: readonly LoadSample[];
  readonly queueSamples: readonly QueueSample[];
  /**
   * One entry per completed car move — the raw input to {@link EnergyStatistics}.
   *
   * Optional, so every record written before the energy axis existed still parses and every
   * stored Phase 5 / 6 record replays unchanged. Absent means *not measured*, and
   * `summarizeRun` reports `energy.measured: false` with `NaN` figures rather than zeros; see
   * {@link EnergyStatistics}.
   *
   * Recorded rather than reconstructed. Passenger records say where *passengers* went; they
   * cannot say where the *cars* went, and the difference is precisely the deadheading that
   * stage 7's repositioning spends energy on — the one stage an energy axis exists to price.
   */
  readonly travelSamples?: readonly TravelSample[] | undefined;
  /** Free-form provenance: weight vector id, sweep coordinates, anything Phase 3 wants back. */
  readonly metadata?: Readonly<Record<string, string | number | boolean>> | undefined;
}

/**
 * The master seed as a `bigint`, ready for `new StreamSet(...)`.
 *
 * @throws MetricsError if the stored seed is not a non-negative decimal integer — an
 *   unreplayable record is a broken record, not a record with a cosmetic flaw.
 */
export function runSeed(record: Pick<RunRecord, 'seed' | 'runId'>): bigint {
  if (!/^\d+$/.test(record.seed)) {
    throw new MetricsError(
      `Run "${record.runId}" carries seed "${record.seed}", which is not a decimal integer. Every run record must carry the seed that produced it (CLAUDE.md invariant 5) or it cannot be replayed.`,
    );
  }
  return BigInt(record.seed);
}

