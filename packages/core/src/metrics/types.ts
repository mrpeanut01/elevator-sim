/**
 * The vocabulary of measurement: what a run records, and what a run summarizes to.
 *
 * docs/03-traffic-and-statistics.md § Part 5 is unambiguous about the shape of this module:
 *
 * > Persist **per-run records, not aggregates**, with the seed attached, so any run can be
 * > replayed exactly and results re-analyzed without re-simulating.
 *
 * So a {@link RunRecord} is a *dataset*, not a report. It carries one {@link PassengerRecord}
 * per leg, the raw load and queue samples, and the seed — and nothing derived. Every headline
 * number (AWT, WT95, % > 60 s, TTD, handling capacity, saturation) is computed from it by
 * `summarize.ts`, which means Phase 3 can re-window, re-threshold or re-percentile a stored
 * run without re-simulating it. Anything stored *and* derived would be a second source of
 * truth that could drift from the first.
 *
 * ## Two rules that decide most of the design
 *
 * **1. Window membership is by arrival time, and it is half-open.** A leg belongs to the
 * window `[startS, endS)` iff `startS <= arrivedAt < endS`, and a *journey* belongs to it iff
 * its first leg does. Arrival time is chosen over boarding or alighting time for a reason
 * that is easy to miss and expensive to get wrong: arrival time is generated by the traffic
 * model and is **identical across every dispatcher under comparison** (common random
 * numbers), whereas boarding time is an *output* of the dispatcher. Selecting by boarding
 * time would let a slow dispatcher push its own worst passengers past the window boundary and
 * report a better AWT for being worse. Half-open so that adjacent windows partition a run
 * exactly once, with no passenger counted twice and none dropped.
 *
 * The one deliberate exception is {@link HandlingCapacity}, which is a *throughput* measure
 * and must count events that occurred during the window rather than a cohort that arrived
 * during it. It says so on the type.
 *
 * **2. No mean for a diverging queue.** {@link SaturationDiagnosis} exists so that a saturated
 * configuration is reported as saturated rather than as an AWT. {@link RunSummary.awtIsValid}
 * is the flag Phase 3 reads to suppress the confidence interval.
 *
 * ## Conventions (see CLAUDE.md)
 *
 * - Time is simulated seconds from the kernel; nothing here reads a wall clock (invariant 3).
 * - Every field is `readonly`, every collection a copy.
 * - Empty statistics report `NaN`, never `0`. "No passengers waited" and "passengers waited
 *   zero seconds" are different facts, and a downstream confidence interval must not be able
 *   to confuse them.
 */

