#!/usr/bin/env node
/**
 * Writes the Rush's wave-model templates into `data/traffic-profiles.json`.
 *
 * `endless-rush` (the climb) is authored by hand and is not touched. Every other wave model is the
 * same climb with a different rhythm inside each three-minute wave, so it is generated from the
 * climb's own arithmetic (`packages/core/src/sim/rush.ts#RUSH_STREAM`) and the shape numbers in
 * `data/rush-cards.json`. Run it after changing either:
 *
 *   node scripts/generate-rush-wave-models.mjs
 *
 * A model's phases are intensities against that model's own peak, because a template may not exceed
 * 1 (`config/demandPhases.ts` rule 3). The peak is `peakFactor` × wave 30's rate, and the run's
 * arrival rate is set to it by `rushTopRatePctPop5min`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TRAFFIC_PATH = join(ROOT, 'data', 'traffic-profiles.json');
const CARDS_PATH = join(ROOT, 'data', 'rush-cards.json');

/** `RUSH_STREAM`'s constants. `packages/core/src/sim/rushCards.test.ts` holds the two in agreement. */
const STREAM = { lengthS: 5400, waveS: 180, baseRate: 0.34, waveStep: 0.11 };
const WAVES = STREAM.lengthS / STREAM.waveS;
/** The climb's own ramp between waves, seconds. */
const RAMP_S = 30;

const round6 = (value) => Math.round(value * 1e6) / 1e6;
const waveRate = (index) => STREAM.baseRate + index * STREAM.waveStep;
const topRate = waveRate(WAVES - 1);

function splitOf(mix) {
  return { incoming: mix.incoming, outgoing: mix.outgoing, interfloor: mix.interfloor };
}

/**
 * One model's phase list. Each wave is `beats` equal stretches, each holding the wave's rate times
 * that beat's factor and that beat's mix, with a 30 s ramp into the next stretch. The beat factors
 * average 1, so a wave brings the people the climb's wave brings.
 */
function phasesOf(model) {
  const beats = model.beats;
  const beatS = STREAM.waveS / beats.length;
  const peak = topRate * model.peakFactor;
  const knots = [];
  for (let wave = 0; wave < WAVES; wave += 1) {
    for (const [index, beat] of beats.entries()) {
      const mix = model.mixes[beat.mix];
      if (mix === undefined) throw new Error(`${model.id}: no mix "${beat.mix}"`);
      knots.push({ startS: wave * STREAM.waveS + index * beatS, rate: waveRate(wave) * beat.factor, mix });
    }
  }
  const phases = [];
  for (const [index, knot] of knots.entries()) {
    const next = knots[index + 1];
    const endS = next === undefined ? STREAM.lengthS : next.startS;
    const intensity = round6(knot.rate / peak);
    const holdEndS = next === undefined ? endS : endS - RAMP_S;
    phases.push({
      startMin: knot.startS / 60,
      endMin: holdEndS / 60,
      startIntensity: intensity,
      endIntensity: intensity,
      startSplit: splitOf(knot.mix),
      endSplit: splitOf(knot.mix),
    });
    if (next !== undefined) {
      phases.push({
        startMin: holdEndS / 60,
        endMin: endS / 60,
        startIntensity: intensity,
        endIntensity: round6(next.rate / peak),
        startSplit: splitOf(knot.mix),
        endSplit: splitOf(next.mix),
      });
    }
  }
  return phases;
}

const cards = JSON.parse(readFileSync(CARDS_PATH, 'utf8'));
/*
 * The file is spliced as text and never re-serialised: it writes `1.0` and `0.0` where
 * `JSON.stringify` writes `1` and `0`, and a whole-file rewrite would touch every hand-authored
 * record. A generated record sits at the end of `demandTemplates`, from `,\n    {\n      "id": …` to
 * its closing brace at the same indent.
 */
let text = readFileSync(TRAFFIC_PATH, 'utf8');
const LIST_END = '\n  ],\n  "passengerMass"';

for (const model of cards.waveModels) {
  if (model.beats === undefined) continue;
  const record = {
    id: model.templateId,
    name: `Rush: ${model.name}`,
    recommended: false,
    selectable: false,
    durationMin: STREAM.lengthS / 60,
    startOfDayMin: 480,
    reportWindow: 'full-run',
    shape: model.shape,
    $comment:
      'GENERATED by scripts/generate-rush-wave-models.mjs from data/rush-cards.json and never edited by hand. ' +
      'A Rush wave model (DECISIONS.md section D1640): the endless-rush climb, wave for wave, with a different ' +
      'rhythm inside each three-minute wave. Intensity is against this model\'s own peak, peakFactor x wave 30\'s ' +
      'rate, which packages/core/src/sim/rushCards.ts converts to the run\'s arrival rate. NOT CITED and a ' +
      'demonstration on the footing endless-rush states (section D478): the rate leaves every declared band on ' +
      'purpose. DERIVED: each stretch holds its rate and ramps to the next over its last 30 s, because rule 6 of ' +
      'config/demandPhases.ts admits no step, which is the compromise endless-rush states. CLOCK, NOT CITED: 08:00 ' +
      'is a placement, the hour endless-rush opens at, so every card opens where the climb does. selectable is ' +
      'false, so no list offers it and no judged surface names it (docs/35 PM-RU2).',
    phases: phasesOf(model),
  };
  const open = `,\n    {\n      "id": ${JSON.stringify(record.id)},`;
  const from = text.indexOf(open);
  if (from !== -1) {
    const to = text.indexOf('\n    }', from + open.length);
    if (to === -1) throw new Error(`${record.id}: no closing brace`);
    text = text.slice(0, from) + text.slice(to + '\n    }'.length);
  }
  const at = text.indexOf(LIST_END);
  if (at === -1) throw new Error('demandTemplates is not followed by passengerMass');
  /* One phase a line: a generated list is read by a machine, and 400 phases at one field a line is 6 700 lines. */
  const { phases, ...head } = record;
  const lines = phases.map((phase) => `        ${JSON.stringify(phase)}`).join(',\n');
  const body = `${JSON.stringify(head, null, 2).replace(/\n\}$/u, '').replace(/\n/gu, '\n    ')},\n      "phases": [\n${lines}\n      ]\n    }`;
  text = `${text.slice(0, at)},\n    ${body}${text.slice(at)}`;
}

JSON.parse(text);
writeFileSync(TRAFFIC_PATH, text);
